def _count_episodes(mask: np.ndarray) -> int:
    """Count contiguous True segments in a 1D boolean array."""
    if mask.size == 0:
        return 0
    m = mask.astype(np.int32)
    starts = (m == 1) & (np.roll(m, 1) == 0)
    starts[0] = (m[0] == 1)
    return int(np.sum(starts))


def compute_run_metrics(logs: SwarmLogs, labels: FailureLabels, swarm_indices: List[int], collision_dist: float) -> Dict:
    """Compute simple, robust, report-friendly metrics from GT logs."""
    T, N = labels.collision.shape

    # Global min distance (GT)
    dists = compute_pairwise_dists(logs.data["gt_pos"])  # [T,N,N]
    for t in range(T):
        np.fill_diagonal(dists[t], np.inf)
    min_global = np.min(dists, axis=(1, 2))  # [T]
    collision_mask = min_global < float(collision_dist)
    collision_episodes = _count_episodes(collision_mask)

    # Swarm formation error stats (swarm only)
    swarm_indices = list(swarm_indices)
    fe = labels.formation_error[:, :]  # [T,N] (0 for independent drones)
    fe_swarm = fe[:, swarm_indices] if len(swarm_indices) > 0 else np.zeros((T, 0), dtype=np.float32)

    speed = labels.speed  # [T,N]

    out = {
        "T": int(T),
        "N": int(N),
        "dt_median": float(np.median(np.diff(logs.times))) if len(logs.times) > 1 else None,
        "min_interdrone_distance_min": float(np.min(min_global)),
        "min_interdrone_distance_p05": float(np.quantile(min_global, 0.05)),
        "collision_steps_frac": float(np.mean(collision_mask)),
        "collision_episodes": int(collision_episodes),
        "swarm_formation_error_mean": float(np.mean(fe_swarm)) if fe_swarm.size else 0.0,
        "swarm_formation_error_p95": float(np.quantile(fe_swarm, 0.95)) if fe_swarm.size else 0.0,
        "swarm_formation_error_max": float(np.max(fe_swarm)) if fe_swarm.size else 0.0,
    }

    # Per-drone metrics
    per = []
    for i, name in enumerate(logs.drone_names):
        per.append({
            "drone": name,
            "speed_mean": float(np.mean(speed[:, i])),
            "speed_p95": float(np.quantile(speed[:, i], 0.95)),
            "speed_max": float(np.max(speed[:, i])),
            "formation_error_mean": float(np.mean(fe[:, i])),
            "formation_error_p95": float(np.quantile(fe[:, i], 0.95)),
            "collision_steps_frac": float(np.mean(labels.collision[:, i] > 0.5)),
            "gnss_deg_steps_frac": float(np.mean(labels.gnss_degradation[:, i] > 0.5)),
            "wind_loss_steps_frac": float(np.mean(labels.wind_loss[:, i] > 0.5)),
            "suboptimal_steps_frac": float(np.mean(labels.suboptimal_traj[:, i] > 0.5)),
        })
    out["per_drone"] = per
    return out


