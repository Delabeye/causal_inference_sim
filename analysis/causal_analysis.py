def set_seed(seed: int) -> None:
    """Set RNG seeds for Python, NumPy, and PyTorch."""
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def set_torch_threads(n: int) -> None:
    """
    PyTorch can be *very* slow on tiny tensors when many CPU threads are enabled.
    Setting n=1 (or 2) is often 10x-1000x faster for this kind of NRI pipeline.
    """
    n = int(max(1, n))
    try:
        torch.set_num_threads(n)
    except Exception:
        pass
    try:
        torch.set_num_interop_threads(n)
    except Exception:
        pass


