@dataclass
class FailureLabels:
    """Binary labels per event type + auxiliary signals."""
    # Each is [T, N] (binary)
    collision: np.ndarray
    formation_loss: np.ndarray
    gnss_degradation: np.ndarray
    wind_loss: np.ndarray
    suboptimal_traj: np.ndarray

    # Auxiliary signals
    formation_error: np.ndarray      # [T, N]
    min_pairwise_dist: np.ndarray    # [T, N]
    speed: np.ndarray                # [T, N]


def compute_pairwise_dists(pos: np.ndarray) -> np.ndarray:
    """Compute pairwise distances: pos [T,N,3] -> dists [T,N,N]."""
    T, N, _ = pos.shape
    d = pos[:, :, None, :] - pos[:, None, :, :]
    d2 = np.sum(d * d, axis=-1)
    dist = np.sqrt(np.maximum(d2, 0.0))
    return dist


def compute_proximity_fraction(pos: np.ndarray, radius: float) -> np.ndarray:
    """
    Fraction of time each pair (i,j) is within `radius` (i receives from j).

    Returns:
        frac: [N, N] in [0,1], diag=0
    """
    dists = compute_pairwise_dists(pos)  # [T,N,N]
    T, N, _ = dists.shape
    for t in range(T):
        np.fill_diagonal(dists[t], np.inf)
    close = (dists < float(radius))
    frac = close.mean(axis=0).astype(np.float32)
    np.fill_diagonal(frac, 0.0)
    return frac


def _parse_indices(spec: str, n: int) -> List[int]:
    """Parse a comma-separated list of indices; keep only unique valid indices in [0, n-1]."""
    if spec is None:
        return []
    spec = str(spec).strip()
    if not spec:
        return []
    out = []
    for part in spec.split(','):
        part = part.strip()
        if not part:
            continue
        try:
            idx = int(part)
        except ValueError:
            continue
        if 0 <= idx < n and idx not in out:
            out.append(idx)
    return out


def _apply_persistence(x: np.ndarray, min_steps: int) -> np.ndarray:
    """Enforce `min_steps` consecutive 1s on a binary array x: [T,N]."""
    if min_steps <= 1:
        return x.astype(np.int32)
    T, N = x.shape
    y = np.zeros_like(x, dtype=np.int32)
    for i in range(N):
        run = 0
        for t in range(T):
            if x[t, i] == 1:
                run += 1
            else:
                run = 0
            if run >= min_steps:
                y[t, i] = 1
    return y


def detect_failures(
    logs: SwarmLogs,
    leader_index: int = 0,
    collision_dist: float = 0.6,
    formation_thresh: float = 1.0,
    gnss_quantile: float = 0.95,
    wind_quantile: float = 0.95,
    suboptimal_quantile: float = 0.95,
    suboptimal_persist_steps: int = 5,
    event_persist_steps: int = 5,
    swarm_indices: Optional[List[int]] = None,
    independent_indices: Optional[List[int]] = None,
    target_jump_thresh: float = 20.0,
    smooth_window: int = 5,
) -> FailureLabels:
    """
    Mission-aware detection heuristics:

    - collision: min inter-drone distance < collision_dist

    - formation_loss: computed *only* for the swarm (swarm_indices).
      We measure "shape deformation" via intra-swarm inter-drone distances
      (translation/rotation invariant). For drones outside the swarm (e.g., drone_3),
      formation_error = 0 and formation_loss = 0.

    - gnss_degradation: global threshold (quantile over all values) + persistence

    - wind_loss: global wind_mag threshold + positive slope of smoothed tracking_error + persistence

    - suboptimal_traj: smoothed tracking_error > global threshold + persistence,
      while ignoring "target jumps" (waypoint artifacts).
    """
    pos = logs.data["gt_pos"]  # [T,N,3]
    vel = logs.data["gt_vel"]
    wind_mag = logs.data["wind_mag"]
    gnss_err = logs.data["gnss_error_mag"]
    track_err = logs.data["tracking_error_mag"]
    target_pos = logs.data.get("target_pos", None)

    T, N, _ = pos.shape

    if swarm_indices is None:
        # Default explicit swarm {0,1,2} if possible
        swarm_indices = [i for i in [0, 1, 2] if i < N]
    if independent_indices is None:
        independent_indices = [3] if N > 3 else []
    # Keep only valid unique indices
    swarm_indices = [i for i in swarm_indices if 0 <= i < N]
    independent_indices = [i for i in independent_indices if 0 <= i < N]

    # Pairwise distances
    dists = compute_pairwise_dists(pos)  # [T,N,N]
    for t in range(T):
        np.fill_diagonal(dists[t], np.inf)
    min_dist = np.min(dists, axis=-1)  # [T,N]

    collision = (min_dist < collision_dist).astype(np.int32)

    # --- Formation error: only within swarm ---
    formation_error = np.zeros((T, N), dtype=np.float32)
    formation_loss = np.zeros((T, N), dtype=np.int32)
    if len(swarm_indices) >= 2:
        d0 = dists[0]  # [N,N]
        # For each swarm drone i, average absolute deviation of distances to other swarm drones
        for i in swarm_indices:
            js = [j for j in swarm_indices if j != i]
            if not js:
                continue
            diff = np.abs(dists[:, i, js] - d0[i, js][None, :])  # [T,|js|]
            formation_error[:, i] = np.mean(diff, axis=-1)
        formation_loss[:, swarm_indices] = (formation_error[:, swarm_indices] > formation_thresh).astype(np.int32)

    # --- GNSS degradation: GLOBAL threshold + persistence ---
    gnss_thr = float(np.quantile(gnss_err.reshape(-1), gnss_quantile))
    gnss_degradation = (gnss_err > gnss_thr).astype(np.int32)
    gnss_degradation = _apply_persistence(gnss_degradation, event_persist_steps)

    # --- Smooth tracking error ---
    track_smooth = track_err.copy().astype(np.float32)
    if smooth_window and smooth_window > 1:
        # Simple rolling median per drone
        w = int(smooth_window)
        pad = w // 2
        for i in range(N):
            x = track_err[:, i]
            xp = np.pad(x, (pad, pad), mode='edge')
            med = np.zeros_like(x)
            for t in range(T):
                med[t] = np.median(xp[t:t+w])
            track_smooth[:, i] = med

    # --- Wind loss: GLOBAL wind threshold + positive slope of smoothed tracking error + persistence ---
    wind_thr = float(np.quantile(wind_mag.reshape(-1), wind_quantile))
    d_track = np.zeros_like(track_smooth)
    d_track[1:] = (track_smooth[1:] - track_smooth[:-1]) / max(logs.dt, 1e-6)
    wind_loss = ((wind_mag > wind_thr) & (d_track > 0.5)).astype(np.int32)
    wind_loss = _apply_persistence(wind_loss, event_persist_steps)

    # --- Suboptimal trajectory: GLOBAL threshold + persistence, ignore target jumps ---
    jump_mask = np.zeros((T, N), dtype=bool)
    if target_pos is not None:
        # Mark timesteps where target jumps too far in one step
        dtar = np.zeros((T, N), dtype=np.float32)
        dtar[1:] = np.linalg.norm(target_pos[1:] - target_pos[:-1], axis=-1)
        jump_mask = dtar > float(target_jump_thresh)

    # Compute threshold excluding jump timesteps (flatten)
    valid_vals = track_smooth[~jump_mask]
    if valid_vals.size < 10:
        sub_thr = float(np.quantile(track_smooth.reshape(-1), suboptimal_quantile))
    else:
        sub_thr = float(np.quantile(valid_vals, suboptimal_quantile))

    suboptimal = (track_smooth > sub_thr).astype(np.int32)
    suboptimal[jump_mask] = 0
    suboptimal = _apply_persistence(suboptimal, suboptimal_persist_steps)

    speed = np.linalg.norm(vel, axis=-1)  # [T,N]

    return FailureLabels(
        collision=collision,
        formation_loss=formation_loss,
        gnss_degradation=gnss_degradation,
        wind_loss=wind_loss,
        suboptimal_traj=suboptimal,
        formation_error=formation_error.astype(np.float32),
        min_pairwise_dist=min_dist.astype(np.float32),
        speed=speed.astype(np.float32),
    )


