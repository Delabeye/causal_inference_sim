def plot_event_probas(
    times: np.ndarray,
    probas: Dict[str, np.ndarray],
    labels: Optional[FailureLabels],
    names: List[str],
    out_dir: str,
    events: Optional[List[str]] = None,
    smooth_window_s: float = 0.5,
) -> None:
    """
    Save one figure per drone with event probability time-series.

    - One subplot per event (readable).
    - Optional smoothing (raw trace kept faint).
    - Optionally overlays the binary ground-truth label as background + step line.
    """
    if events is None:
        preferred = ["collision", "formation_loss", "gnss_degradation", "wind_loss", "suboptimal_traj"]
        events = [e for e in preferred if e in probas] + [e for e in probas.keys() if e not in preferred]

    T, N = next(iter(probas.values())).shape
    if len(times) >= 2:
        dt = float(np.median(np.diff(times)))
    else:
        dt = 0.1
    win = max(1, int(round(smooth_window_s / max(dt, 1e-6))))
    kernel = np.ones(win, dtype=np.float32) / float(win)

    def smooth(x: np.ndarray) -> np.ndarray:
        if win <= 1:
            return x
        return np.convolve(x, kernel, mode="same")

    for i in range(N):
        fig_h = max(3.0, 1.5 * len(events))
        fig, axes = plt.subplots(len(events), 1, figsize=(11, fig_h), sharex=True)
        if len(events) == 1:
            axes = [axes]

        for k, ev in enumerate(events):
            ax = axes[k]
            y = probas[ev][:, i]
            ys = smooth(y)

            ax.plot(times, ys, linewidth=1.8, label="pred (smoothed)")
            ax.plot(times, y, linewidth=0.8, alpha=0.25, label="pred (raw)")

            if labels is not None and hasattr(labels, ev):
                lab = getattr(labels, ev)[:, i].astype(np.float32)
                ax.fill_between(times, 0.0, 1.0, where=lab > 0.5, step="pre", alpha=0.08)
                ax.plot(times, 0.95 * lab, drawstyle="steps-pre", linewidth=0.9, alpha=0.35, label="label")

            ax.set_ylim(0.0, 1.0)
            ax.set_ylabel(ev, fontsize=9)
            ax.grid(True, linestyle=":", alpha=0.6)

            if k == 0:
                ax.legend(loc="upper right", fontsize=8, ncol=3)

        axes[-1].set_xlabel("time [s]")
        fig.suptitle(f"Event probabilities - {names[i]}", fontsize=12)
        fig.tight_layout(rect=[0, 0, 1, 0.95])
        fig.savefig(os.path.join(out_dir, f"event_probabilities_{names[i]}.png"), dpi=180)
        plt.close(fig)


