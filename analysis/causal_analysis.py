def run_pipeline(args: argparse.Namespace) -> Dict:
    """Run the full analysis pipeline and save outputs."""
    ensure_dir(args.output_dir)

    logs = load_swarm_logs(args.log_dir, downsample=args.downsample)
    names = logs.drone_names
    N = len(names)
    print(f"[Load] N={N} drones, T={len(logs.times)} steps, dt≈{logs.dt:.4f}s, downsample={args.downsample}")

    swarm_idxs = _parse_indices(args.swarm_indices, N)
    ind_idxs = _parse_indices(args.independent_indices, N)

    labels = detect_failures(
        logs,
        leader_index=args.leader_index,
        collision_dist=args.collision_dist,
        formation_thresh=args.formation_thresh,
        gnss_quantile=args.gnss_quantile,
        wind_quantile=args.wind_quantile,
        suboptimal_quantile=args.suboptimal_quantile,
        suboptimal_persist_steps=args.suboptimal_persist,
        event_persist_steps=args.event_persist,
        swarm_indices=swarm_idxs,
        independent_indices=ind_idxs,
        target_jump_thresh=args.target_jump_thresh,
        smooth_window=args.smooth_window,
    )

    # ------------------ Report-friendly GT outputs (recommended) ------------------
    out = args.output_dir

    metrics = compute_run_metrics(logs, labels, swarm_indices=swarm_idxs, collision_dist=float(args.collision_dist))
    # Save metrics (JSON + CSV)
    with open(os.path.join(out, "metrics_summary.json"), "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2, ensure_ascii=False)
    pd.DataFrame(metrics.get("per_drone", [])).to_csv(os.path.join(out, "metrics_per_drone.csv"), index=False)

    # GT-derived time-series (always useful)
    plot_timeseries_per_drone(
        logs.times,
        labels.formation_error,
        names,
        title="Formation error per drone (computed only within swarm: indices in --swarm_indices)",
        ylabel="formation error [m]",
        out_path=os.path.join(out, "formation_error_timeseries.png"),
        y_min=0.0,
    )
    plot_timeseries_per_drone(
        logs.times,
        labels.speed,
        names,
        title="Speed per drone vs time (GT velocity)",
        ylabel="speed [m/s]",
        out_path=os.path.join(out, "speed_timeseries.png"),
        y_min=0.0,
    )
    plot_min_distance_global(
        logs.times,
        logs.data["gt_pos"],
        collision_dist=float(args.collision_dist),
        out_path=os.path.join(out, "min_interdrone_distance_gt.png"),
    )

    # Binary event timeline (often more interpretable than many matrices)
    plot_event_timeline(logs.times, labels, names, out_path=os.path.join(out, "event_timeline.png"))

    # Exogenous signal timelines (useful for causal narratives / ablations)
    plot_signal_timeseries(
        logs.times,
        logs.data["gnss_error_mag"],
        names,
        title="GNSS error magnitude per drone",
        ylabel="gnss_error_mag [m]",
        out_path=os.path.join(out, "gnss_error_timeseries.png"),
    )
    plot_signal_timeseries(
        logs.times,
        logs.data["wind_mag"],
        names,
        title="Wind magnitude per drone",
        ylabel="wind_mag [m/s]",
        out_path=os.path.join(out, "wind_mag_timeseries.png"),
    )

    if getattr(args, "mode", "lite") == "lite":
        print("[Mode] lite: skipping NRI / Granger / root-cause / impact matrices. Use --mode full to enable them.")
        return metrics

    # Build dataset for NRI
    ds = build_sequence_dataset(logs, use_measured=args.use_measured)

    # Train NRI
    nri_res = train_nri(
        dataset=ds,
        n_nodes=N,
        seq_len=args.seq_len,
        n_edge_types=args.n_edge_types,
        hidden=args.hidden,
        dropout=args.dropout,
        batch_size=args.batch_size,
        nri_steps=args.nri_steps,
        lr=args.lr,
        tau_start=args.tau_start,
        tau_end=args.tau_end,
        tau_anneal_steps=args.tau_anneal_steps,
        max_train_windows=args.max_train_windows,
        device=args.device,
        torch_threads=args.torch_threads,
        seed=args.seed,
        verbose_every=args.verbose_every,
    )

    # --- Proximity-weighted edges (physics-aware gating) ---
    proximity_frac = compute_proximity_fraction(logs.data["gt_pos"], args.proximity_radius)
    edge_probs_raw = nri_res.edge_probs.astype(np.float32)
    edge_probs_effective = (edge_probs_raw * proximity_frac).astype(np.float32)

    # ------------------ save matrices ------------------
    out = args.output_dir

    # "edge_probs_one_minus" keeps prior naming; it is (1 - edge_probs_raw) here, used for debugging/visualization
    edge_probs_one_minus = (1.0 - edge_probs_raw).astype(np.float32)

    np.save(os.path.join(out, "nri_edge_probs_raw.npy"), edge_probs_raw)
    np.save(os.path.join(out, "nri_edge_probs.npy"), edge_probs_one_minus)
    np.save(os.path.join(out, "nri_proximity_fraction.npy"), proximity_frac)
    np.save(os.path.join(out, "nri_edge_effective.npy"), edge_probs_effective)

    save_matrix_csv(edge_probs_raw, row_names=names, col_names=names, out_path=os.path.join(out, "nri_edge_probs_raw.csv"))
    save_matrix_csv(edge_probs_one_minus, row_names=names, col_names=names, out_path=os.path.join(out, "nri_edge_probs.csv"))
    save_matrix_csv(proximity_frac, row_names=names, col_names=names, out_path=os.path.join(out, "nri_proximity_fraction.csv"))
    save_matrix_csv(edge_probs_effective, row_names=names, col_names=names, out_path=os.path.join(out, "nri_edge_effective.csv"))

    # ------------------ figures ------------------
    plot_loss_curve(nri_res.nri_loss_curve, os.path.join(out, "nri_training_loss.png"))

    # Edge visualizations:
    # 1) Main heatmap requested: 1 - raw
    plot_heatmap(
        edge_probs_one_minus,
        title="1 - NRI interaction score (receiver i, sender j)",
        xlabel="sender j",
        ylabel="receiver i",
        xticks=names,
        yticks=names,
        out_path=os.path.join(out, "nri_edge_probs_heatmap.png"),
        vmin=0.0,
        vmax=1.0,
    )

    # 2) Raw heatmap (debug)
    plot_heatmap(
        edge_probs_raw,
        title="NRI inferred interaction score RAW (receiver i, sender j)",
        xlabel="sender j",
        ylabel="receiver i",
        xticks=names,
        yticks=names,
        out_path=os.path.join(out, "nri_edge_probs_raw_heatmap.png"),
        vmin=0.0,
        vmax=1.0,
    )

    # 3) Proximity fraction heatmap
    plot_heatmap(
        proximity_frac,
        title=f"Proximity fraction P(dist<{args.proximity_radius:.2f}m) (receiver i, sender j)",
        xlabel="sender j",
        ylabel="receiver i",
        xticks=names,
        yticks=names,
        out_path=os.path.join(out, "nri_proximity_fraction_heatmap.png"),
        vmin=0.0,
        vmax=1.0,
    )

    # 4) Effective edges: raw * proximity
    plot_heatmap(
        edge_probs_effective,
        title="Effective interaction score = RAW * proximity (receiver i, sender j)",
        xlabel="sender j",
        ylabel="receiver i",
        xticks=names,
        yticks=names,
        out_path=os.path.join(out, "nri_edge_effective_heatmap.png"),
        vmin=0.0,
        vmax=1.0,
    )

    # High-level summary for reporting
    summary = {
        "log_dir": args.log_dir,
        "output_dir": args.output_dir,
        "n_drones": N,
        "n_steps": int(len(logs.times)),
        "dt": logs.dt,
        "nri": {
            "seq_len": args.seq_len,
            "n_edge_types": args.n_edge_types,
            "hidden": args.hidden,
            "nri_steps": args.nri_steps,
            "final_train_mse": float(np.mean(nri_res.nri_loss_curve[-50:])) if len(nri_res.nri_loss_curve) >= 50 else float(np.mean(nri_res.nri_loss_curve)),
        },
        "detection": {
            "collision_dist": args.collision_dist,
            "formation_thresh": args.formation_thresh,
            "gnss_quantile": args.gnss_quantile,
            "wind_quantile": args.wind_quantile,
            "suboptimal_quantile": args.suboptimal_quantile,
            "event_persist": args.event_persist,
            "suboptimal_persist": args.suboptimal_persist,
            "smooth_window": args.smooth_window,
            "target_jump_thresh": args.target_jump_thresh,
            "swarm_indices": swarm_idxs,
            "independent_indices": ind_idxs,
        },
        "proximity_radius": args.proximity_radius,
        "top_edges_effective": top_edges_from_matrix(edge_probs_effective, names, k=10),
        "top_edges_raw": top_edges_from_matrix(edge_probs_raw, names, k=10),
    }

    with open(os.path.join(out, "summary_report.json"), "w", encoding="utf-8") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)

    print(f"[Done] Outputs saved to: {os.path.abspath(out)}")
    return summary


def top_edges_from_matrix(mat: np.ndarray, names: List[str], k: int = 10) -> List[Dict]:
    """Return the top-k directed edges (by weight) from a square matrix."""
    N = len(names)
    edges = []
    for i in range(N):
        for j in range(N):
            if i == j:
                continue
            edges.append((float(mat[i, j]), j, i))  # w, sender, receiver
    edges.sort(reverse=True, key=lambda x: x[0])
    out = []
    for w, j, i in edges[:k]:
        out.append({"sender": names[j], "receiver": names[i], "weight": w})
    return out


